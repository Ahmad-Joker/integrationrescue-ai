"""Isolated patch workspace: copy repo, apply bounded edits, run tests, replay workflow."""

from __future__ import annotations

import difflib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any

from ..security.policy import PolicyViolation, safe_relpath
from ..simulators.sync_service import make_subscriber
from ..simulators.world import World

TEST_TIMEOUT_S = 90


def copy_repo(src: Path, dest: Path) -> Path:
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(src, dest, ignore=shutil.ignore_patterns("__pycache__", ".pytest_cache"))
    return dest


def apply_edits(repo: Path, edits: list[dict[str, Any]]) -> str:
    """Apply already-reviewed edits inside repo. Returns a unified diff."""
    diffs: list[str] = []
    for e in edits:
        target = safe_relpath(repo, e["path"])
        before = target.read_text(encoding="utf-8") if target.exists() else ""
        if e["op"] == "json_set":
            data = json.loads(before) if before else {}
            node = data
            for key in e["key_path"][:-1]:
                node = node.setdefault(key, {})
            node[e["key_path"][-1]] = e["value"]
            after = json.dumps(data, indent=2) + "\n"
        elif e["op"] == "replace":
            count = before.count(e["old"])
            if count != 1:
                raise PolicyViolation(f"replace target must occur exactly once in {e['path']} (found {count})")
            after = before.replace(e["old"], e["new"])
        else:
            raise PolicyViolation(f"unsupported op {e['op']}")
        target.write_text(after, encoding="utf-8")
        diffs.extend(difflib.unified_diff(before.splitlines(True), after.splitlines(True),
                                          f"a/{e['path']}", f"b/{e['path']}"))
    return "".join(diffs)


def run_tests(repo: Path, test_paths: list[str] | None = None) -> dict[str, Any]:
    env = {k: v for k, v in os.environ.items()
           if k.upper() in {"SYSTEMROOT", "SYSTEMDRIVE", "WINDIR", "TEMP", "TMP", "PATH"}}
    cmd = [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", *(test_paths or ["tests"])]
    try:
        proc = subprocess.run(cmd, cwd=str(repo), capture_output=True, text=True,
                              timeout=TEST_TIMEOUT_S, env=env)
    except subprocess.TimeoutExpired:
        return {"passed": False, "returncode": None, "output": "test run timed out"}
    out = (proc.stdout + proc.stderr)[-4000:]
    return {"passed": proc.returncode == 0, "returncode": proc.returncode, "output": out}


def replay_event(repo: Path, world: World, event_id: str) -> dict[str, Any]:
    """Redeliver an existing billing event through the sync service built from ``repo``.

    Never creates a new charge: replay reuses the stored event only.
    """
    result = world.deliver(event_id, make_subscriber(repo))
    return {"event_id": event_id, "status": result.final_status, "http_status": result.http_status,
            "attempts": result.attempts}


REGRESSION_TEMPLATE = '''"""Regression test generated by IntegrationRescue for incident {incident_id}.

Replays the captured (redacted) billing event that failed in production and
asserts the entitlement the billing ledger says the customer paid for.
"""

import json
from pathlib import Path

from sync.handler import handle, load_tenant

EVENT = json.loads(Path(__file__).with_name("{fixture_name}").read_text(encoding="utf-8"))


def test_{slug}_paid_event_grants_{plan}():
    out = handle(EVENT, load_tenant(EVENT["data"]["tenant"]))
    assert out["actions"] == [
        {{"op": "set_plan", "customer_id": EVENT["data"]["customer_id"], "plan": "{plan}"}}
    ], out
'''


def write_regression_test(repo: Path, incident_id: str, event: dict[str, Any], expected_plan: str) -> list[str]:
    slug = "incident_" + "".join(ch for ch in incident_id.lower() if ch.isalnum())[:12]
    fixture = {"id": event["id"], "type": event["type"],
               "data": {k: event["data"][k] for k in ("customer_id", "tenant", "lines")}}
    fixture_name = f"fixture_{slug}.json"
    tests = repo / "tests"
    tests.mkdir(exist_ok=True)
    (tests / fixture_name).write_text(json.dumps(fixture, indent=2) + "\n", encoding="utf-8")
    test_name = f"test_regression_{slug}.py"
    (tests / test_name).write_text(REGRESSION_TEMPLATE.format(
        incident_id=incident_id, fixture_name=fixture_name, slug=slug, plan=expected_plan), encoding="utf-8")
    return [f"tests/{test_name}", f"tests/{fixture_name}"]
